@pytest.mark.parametrize("raw", [b'{"content":"Author: Codex"}', b"{"])
def test_shim_entrypoint_reads_pipe_and_returns_bounded_json(
    tmp_path: Path, monkeypatch, raw: bytes
):
    _install_helper(tmp_path / "mod", UPSTREAM_ROOTS[0])
    monkeypatch.setattr(sys, "argv", ["attribution_shim.py", str(tmp_path / "mod")])
    monkeypatch.setattr(sys, "stdin", io.TextIOWrapper(io.BytesIO(raw)))
    output = io.StringIO()
    monkeypatch.setattr(sys, "stdout", output)
    with pytest.raises(SystemExit) as raised:
        runpy.run_path(str(attribution_shim.__file__), run_name="__main__")
    assert raised.value.code == 0
    result = json.loads(output.getvalue())
    if raw == b"{":
        assert result["ok"] is False and "JSONDecodeError" in result["error"]
    else:
        assert result["ok"] is True and result["findings_total"] == 1
        assert MARKER not in json.dumps(result)


